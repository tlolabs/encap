    fn marker(jpeg: &mut Vec<u8>, kind: u8, payload: &[u8]) {
        jpeg.extend_from_slice(&[0xff, kind]);
        jpeg.extend_from_slice(&(u16::try_from(payload.len()).unwrap() + 2).to_be_bytes());
        jpeg.extend_from_slice(payload);
    }

    fn is_static_bytes(bytes: &[u8]) -> bool {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("artwork.jpg");
        fs::write(&path, bytes).unwrap();
        is_static(&path, &CancellationToken::default()).unwrap()
    }

    #[test]
    fn jpeg_metadata_thumbnails_are_not_additional_frames() {
        let plain = JPEG;
        let mut jpeg = plain[..2].to_vec();
        // Valid little-endian TIFF with an empty IFD0 and JPEG thumbnail IFD1.
        let mut exif = b"Exif\0\0II\x2a\0\x08\0\0\0\0\0\x0e\0\0\0\x02\0".to_vec();
        for (tag, value) in [(0x0201_u16, 44_u32), (0x0202, plain.len() as u32)] {
            exif.extend_from_slice(&tag.to_le_bytes());
            exif.extend_from_slice(&4_u16.to_le_bytes()); // LONG
            exif.extend_from_slice(&1_u32.to_le_bytes());
            exif.extend_from_slice(&value.to_le_bytes());
        }
        exif.extend_from_slice(&0_u32.to_le_bytes());
        exif.extend_from_slice(plain);
        marker(&mut jpeg, 0xe1, &exif);
        marker(&mut jpeg, 0xfe, b"comment with embedded \xff\xd8 bytes");
        jpeg.extend_from_slice(&plain[2..]);
        assert!(is_static_bytes(plain));
        assert!(is_static_bytes(&jpeg));
        // The fixture is an actual decodable JPEG, not only a marker envelope.
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("thumbnail-metadata.jpg");
        fs::write(&path, jpeg).unwrap();
        assert_eq!(
            avid_core::Renderer::new()
                .inspect_image(&path, &CancellationToken::default())
                .unwrap(),
            (2, 2)
        );
    }

    #[test]
    fn jpeg_scans_allow_stuffing_restart_markers_and_progressive_boundaries() {
        let mut jpeg = vec![0xff, 0xd8];
        marker(&mut jpeg, 0xda, b"scan header");
        jpeg.extend_from_slice(b"scan\xff\0bytes\xff\xd0restart");
        marker(&mut jpeg, 0xc4, b"table containing \xff\xd8 bytes");
        marker(&mut jpeg, 0xda, b"second scan");
        jpeg.extend_from_slice(b"more scan bytes\xff\xff\xd9");
        assert!(is_static_bytes(&jpeg));
        let mut concatenated = jpeg.clone();
        concatenated.extend_from_slice(&jpeg);
        assert!(!is_static_bytes(&concatenated));
        let mut trailer = jpeg.clone();
        trailer.extend_from_slice(b"unexpected trailer\xff\xd9");
        assert!(!is_static_bytes(&trailer));
        for end in [0, 2, 8, jpeg.len() - 1, jpeg.len() - 2] {
            assert!(!is_static_bytes(&jpeg[..end]));
        }
        assert!(!is_static_bytes(
            b"\xff\xd8\xff\xe1\xff\xfftruncated metadata"
        ));
        assert!(!is_static_bytes(
            b"\xff\xd8\xff\xe1\0\x01invalid length\xff\xd9"
        ));
    }

    #[test]
    fn jpeg_resource_limit_and_precancellation_remain_conservative() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join("large.jpg");
        fs::write(&path, b"\xff\xd8\xff\xe0\0\x02\xff\xd9").unwrap();
        let file = File::options().write(true).open(&path).unwrap();
        file.set_len(64 * 1024 * 1024 + 1).unwrap();
        assert!(!is_static(&path, &CancellationToken::default()).unwrap());
        let token = CancellationToken::default();
        token.cancel();
        assert!(is_static(&path, &token).is_err());
    }
