//! Conservative static-artwork detection; unknown containers retain PerFrame.
//! Dimensions, decoding, corruption, and resource limits remain Core's job.
use crate::{lifecycle, CancellationToken};
use encap_core::{EncapError, Result};
use std::{
    fs::File,
    io::{BufRead, BufReader, Read, Seek, SeekFrom},
    path::Path,
};

pub(crate) fn is_static(path: &Path, token: &CancellationToken) -> Result<bool> {
    lifecycle::check(token)?;
    let mut file = File::open(path).map_err(|source| EncapError::Read {
        path: path.to_path_buf(),
        source,
    })?;
    let mut magic = [0; 8];
    if file.read_exact(&mut magic).is_err() {
        return Ok(false);
    }
    let result = if magic == *b"\x89PNG\r\n\x1a\n" {
        static_png(&mut file, token)
    } else if magic[..2] == [0xff, 0xd8] {
        file.rewind().and_then(|_| static_jpeg(&mut file, token))
    } else {
        // GIF, animated WebP, APNG, and all unrecognized formats retain the
        // original decoder behavior. Extensions never establish staticness.
        Ok(false)
    };
    lifecycle::check(token)?;
    // A malformed container is handed to Core for the normal media diagnostic.
    Ok(result.unwrap_or(false))
}

fn static_png(file: &mut File, token: &CancellationToken) -> std::io::Result<bool> {
    let length = file.metadata()?.len();
    let mut image_data = false;
    for index in 0..4096 {
        if token.is_cancelled() {
            return Ok(false);
        }
        let mut chunk = [0; 8];
        file.read_exact(&mut chunk)?;
        let count = u32::from_be_bytes(chunk[..4].try_into().unwrap()) as u64;
        let kind = &chunk[4..];
        if index == 0 && (kind != b"IHDR" || count != 13) {
            return Ok(false);
        }
        if [b"acTL", b"fcTL", b"fdAT"].contains(&kind.try_into().unwrap()) {
            return Ok(false);
        }
        let next = file.stream_position()?.checked_add(count + 4);
        let Some(next) = next.filter(|offset| *offset <= length) else {
            return Ok(false);
        };
        file.seek(SeekFrom::Start(next))?;
        image_data |= kind == b"IDAT";
        if kind == b"IEND" {
            return Ok(count == 0 && image_data && next == length);
        }
    }
    Ok(false)
}

fn static_jpeg(file: &mut File, token: &CancellationToken) -> std::io::Result<bool> {
    // Metadata segments can contain complete thumbnail JPEGs. Their length
    // fields, rather than raw SOI bytes, distinguish them from another frame.
    let length = file.metadata()?.len();
    if length > 64 * 1024 * 1024 {
        return Ok(false);
    }
    let mut file = BufReader::with_capacity(16 * 1024, file);
    let mut start = [0; 2];
    file.read_exact(&mut start)?;
    if start != [0xff, 0xd8] {
        return Ok(false);
    }
    let mut in_scan = false;
    let mut saw_scan = false;
    loop {
        let Some(marker) = jpeg_marker(&mut file, in_scan, token)? else {
            return Ok(false);
        };
        match marker {
            // Do not accept concatenated MJPEG frames or arbitrary trailing data.
            0xd9 => return Ok(saw_scan && file.stream_position()? == length),
            0xd8 | 0x00 | 0x01 | 0xd0..=0xd7 => return Ok(false),
            _ => {}
        }
        let mut size = [0; 2];
        file.read_exact(&mut size)?;
        let size = u16::from_be_bytes(size);
        if size < 2 {
            return Ok(false);
        }
        let next = file.stream_position()?.checked_add(u64::from(size - 2));
        let Some(next) = next.filter(|offset| *offset <= length) else {
            return Ok(false);
        };
        file.seek(SeekFrom::Start(next))?;
        // DNL can occur inside entropy data; progressive scans can be separated
        // by tables and other length-delimited marker segments.
        in_scan = marker == 0xda || (in_scan && marker == 0xdc);
        saw_scan |= marker == 0xda;
    }
}

fn jpeg_marker<R: BufRead>(
    file: &mut R,
    in_scan: bool,
    token: &CancellationToken,
) -> std::io::Result<Option<u8>> {
    loop {
        if token.is_cancelled() {
            return Ok(None);
        }
        if in_scan {
            // Search buffered entropy data in blocks, retaining bounded I/O and
            // frequent cancellation checks even for a large single scan.
            let bytes = file.fill_buf()?;
            if bytes.is_empty() {
                return Ok(None);
            }
            let count = bytes
                .iter()
                .position(|&byte| byte == 0xff)
                .unwrap_or(bytes.len());
            file.consume(count);
            if count != 0 {
                continue;
            }
        }
        let mut byte = [0];
        file.read_exact(&mut byte)?;
        if byte[0] != 0xff {
            return Ok(None);
        }
        // Repeated 0xff fill bytes are legal between markers.
        loop {
            file.read_exact(&mut byte)?;
            if byte[0] != 0xff {
                break;
            }
            if token.is_cancelled() {
                return Ok(None);
            }
        }
        if in_scan && (byte[0] == 0x00 || (0xd0..=0xd7).contains(&byte[0])) {
            // Stuffed 0xff sample bytes and restart markers remain in this scan.
            continue;
        }
        return Ok(Some(byte[0]));
    }
}

